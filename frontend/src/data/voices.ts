const CLIPS: Record<string, VoiceClip | undefined> = clips

/** The quote as the reel sets it, one entry per word. The clip builder splits
 *  the same way, which is what makes `clip.words[i]` belong to word `i`. */
export function quoteWords(quote: string): string[] {
  return quote.split(/\s+/).filter(Boolean)
}

export function clipFor(voice: Voice): VoiceClip | null {
  return CLIPS[voice.id] ?? null
}

/** The second into the slide at which each word of the quote should light. */
export function wordTimes(voice: Voice): number[] {
  const count = quoteWords(voice.quote).length
  const clip = clipFor(voice)
  if (clip && clip.words.length === count) return clip.words
  // Nothing measured to go on — either there is no clip, or the quote was
  // edited after the clip was cut. Pace the line evenly, at roughly the speed
  // someone would say it, rather than trust timings for a different sentence.
  const span = clip
    ? clip.duration * 0.85
    : Math.min(count * 0.38, (SLIDE_DURATION_MS / 1000) * 0.7)
  return Array.from({ length: count }, (_, i) => 0.5 + (span * i) / count)
}
