// The Hall of Voices — the reel that plays when you sign in.
//
// This is the one file to edit to change what people see. Each entry pairs a
// line from a speech with a *craft note* written in Cadence's own vocabulary
// (pace, pauses, fillers, staying on topic), so the intro teaches something
// instead of only inspiring.
//
// ---------------------------------------------------------------------------
// ABOUT THE CLIPS
// ---------------------------------------------------------------------------
// Each voice is backed by a short clip in frontend/public/voices/, cut tightly
// around the quoted sentence. The clip is the slide's clock: the slide starts
// when the clip starts, each word lights at the moment it is spoken, and the
// reel moves on when the clip ends. What you read and what you hear are the
// same sentence at the same time, because one is timed from the other.
//
// The clips and their timings are generated, not hand-written:
//
//   uv run tools/build_voices.py
//
// finds each `quote` below inside a longer recording (listed per voice in
// tools/voices.sources.json), trims the clip, and writes voiceClips.json with
// the second at which every word is spoken. See public/voices/README.md.
//
// Two rules follow from that:
//
//   * `quote` must be what the speaker actually says, word for word. The
//     builder reports any difference. A paraphrase on screen over the real
//     sentence in your ears reads as broken, so fix the text, not the timing.
//   * After editing a quote, re-run the builder. Timings are matched to the
//     quote by word count; on a mismatch the reel stops trusting them and
//     falls back to an evenly paced reveal.
//
// A voice with no clip (or whose file is missing) still works: the slide runs
// on a timer over the generated backdrop in VoiceBackdrop.tsx. That is a
// designed fallback, not a placeholder.

import clips from './voiceClips.json'

export interface CraftNote {
  /** The rhetorical device, named. */
  technique: string
  /** What a speaker practising today can steal from it. */
  note: string
}

/** Generated by tools/build_voices.py — see voiceClips.json. */
export interface VoiceClip {
  /** Served from public/, e.g. `/voices/king.mp4`. */
  src: string
  /** Length of the clip in seconds. */
  duration: number
  /** False for a sound-only clip: the slide keeps its generated backdrop.
   *  Used where no film of the speech exists and the recording's video is a
   *  slideshow somebody put under the audio. */
  picture: boolean
  /** Second, from the start of the clip, at which each word of the quote is
   *  spoken. One entry per word, in order. */
  words: number[]
}

export interface Voice {
  id: string
  speaker: string
  /** Shown large, and spoken in the clip. Keep it to roughly 30 words — it is
   *  set at display size — and keep it verbatim. */
  quote: string
  occasion: string
  place: string
  year: number
  craft: CraftNote
  /** Duotone wash for the backdrop and the accent rules. */
  accent: string
  initials: string
}

